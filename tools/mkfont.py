#!/usr/bin/env python3
"""Rasterise the glyphs the panel draws into src/font.rs.

The frame puts Russian text on a 6-colour e-paper panel, so a hand-drawn 5x7
ASCII font would not carry it: the transcript and the reply are Cyrillic. This
takes a real font, renders the subset that can actually appear, and emits a
one-bit-per-pixel table plus a sorted index, which is everything the blitter in
`panel.rs` needs.

Deterministic on purpose: same font file, same size, same output. Regenerate
with

    tools/mkfont.py > src/font.rs

`src/font.rs` is checked in, so a build never depends on a host font being
installed; this script is only run when the glyph set or the size changes.
"""

import sys

from PIL import Image, ImageDraw, ImageFont

FONT = "/usr/share/fonts/dejavu-sans-fonts/DejaVuSans.ttf"
PIXEL_SIZE = 26
INK_THRESHOLD = 110

# Everything that can reach the panel: ASCII for titles and numbers, the full
# Russian alphabet in both cases, the Latin-1 letters and accents used by English,
# Finnish and French, a few Latin Extended-A letters those languages also use, and
# the punctuation a transcript or a reply from a language model actually contains.
CHARS = [chr(code) for code in range(0x20, 0x7F)]
CHARS += [chr(code) for code in range(0x410, 0x450)]
CHARS += [chr(code) for code in range(0xC0, 0x100)]
CHARS += ["Ё", "ё", "«", "»", "—", "…", "№", "’", "“", "”", "Œ", "œ", "Š", "š", "Ž", "ž", "€"]


def main() -> int:
    font = ImageFont.truetype(FONT, PIXEL_SIZE)
    ascent, descent = font.getmetrics()
    line_height = ascent + descent

    glyphs = []
    bitmaps = []
    for character in CHARS:
        advance = max(1, round(font.getlength(character)))
        image = Image.new("L", (advance, line_height), 0)
        draw = ImageDraw.Draw(image)
        # Default anchor puts the ascender at the pen, so every glyph shares one
        # baseline without per-glyph bearing bookkeeping.
        draw.text((0, 0), character, fill=255, font=font)
        offset = len(bitmaps)
        rows = []
        for y in range(line_height):
            bits = 0
            byte = 0
            for x in range(advance):
                if image.getpixel((x, y)) >= INK_THRESHOLD:
                    bits |= 0x80 >> (x % 8)
                if x % 8 == 7:
                    rows.append(bits)
                    bits = 0
                    byte += 1
            if advance % 8 != 0:
                rows.append(bits)
        bitmaps.extend(rows)
        glyphs.append((character, advance, offset))

    glyphs.sort(key=lambda item: ord(item[0]))

    out = []
    out.append("//! Generated by `tools/mkfont.py` from DejaVu Sans; do not edit by hand.")
    out.append("//!")
    out.append("//! One bit per pixel, most significant bit leftmost, rows top to bottom, one")
    out.append(f"//! byte-aligned row of `advance` pixels per glyph in a {line_height} pixel cell.")
    out.append("//! The pen advances by `advance` and the glyph's bearings are baked into the")
    out.append("//! bitmap, so drawing needs no metric tables beyond this index.")
    out.append("")
    out.append(f"pub const LINE_HEIGHT: u8 = {line_height};")
    out.append("")
    out.append("pub struct Glyph {")
    out.append("    pub ch: char,")
    out.append("    pub advance: u8,")
    out.append("    /// Index into `BITMAP`, in bytes, of the first row of this glyph.")
    out.append("    pub offset: u32,")
    out.append("}")
    out.append("")
    out.append(f"pub const GLYPHS: [Glyph; {len(glyphs)}] = [")
    for character, advance, offset in glyphs:
        escaped = character.replace("\\", "\\\\").replace("'", "\\'")
        out.append(f"    Glyph {{ ch: '{escaped}', advance: {advance}, offset: {offset} }},")
    out.append("];")
    out.append("")
    out.append("")
    # A static, not a const: clippy rejects large const arrays, and the table is
    # read-only data either way.
    out.append(f"pub static BITMAP: [u8; {len(bitmaps)}] = [")
    for start in range(0, len(bitmaps), 12):
        chunk = ", ".join(f"0x{byte:02x}" for byte in bitmaps[start : start + 12])
        out.append(f"    {chunk},")
    out.append("];")
    out.append("")

    sys.stdout.write("\n".join(out))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
